# Returned statement
def add(a,b):
    ans=a+b
    return ans
total=add(3,4)
print(total)

def sub(a,b):
    ans=a-b
    return ans
total=sub(5,7)
print(total)

def mul(a,b):
    ans=a*b
    return ans
total=mul(8,9)
print(total)

def div(a,b):
    ans=a/b
    return ans
total=div(9,9)
print(total)
